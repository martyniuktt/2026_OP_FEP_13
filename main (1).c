#include <stdio.h>

int main(void) {
    int a, b;
    printf("Введіть два числа через пробіл: ");
    scanf("%d %d", &a, &b);

    // Використання тернарного оператора для порівняння
    a > b ? printf("Перше число (%d) більше за друге (%d)\n", a, b) :
    (a < b ? printf("Перше число (%d менше за друге (%d)\n", a, b) :
             printf("Числа рівні (%d = %d)\n", a, b));

    return 0;
}